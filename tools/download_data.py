"""Downloads the official pretrained 3DGS models and evaluation images into data/.

Only the files the tools use are pulled out of the official archives (over HTTP
range requests, see remote_zip.py), so the full 14 GB + 7 GB zips are never
downloaded. Files already present with the right size are skipped, so the
script can be re-run to resume an interrupted download.

Layout produced:
  data/models/<scene>/{cameras.json, cfg_args, point_cloud/iteration_30000/}
  data/eval/<scene>/{per_view.json, results.json, test/ours_30000/{gt,renders}/}

data/ours, data/report, data/diff and data/bench are generated by the other
tools (benchmark.py, eval_reference.py, compare_images.py), not downloaded.

Usage: python tools/download_data.py [--data-dir data] [--models-only | --eval-only] [scene ...]
"""
import argparse
import io
import os
import shutil
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from remote_zip import HttpRangeFile  # noqa: E402

BASE = "https://repo-sam.inria.fr/fungraph/3d-gaussian-splatting"
MODELS_URL = f"{BASE}/datasets/pretrained/models.zip"
EVAL_URL = f"{BASE}/evaluation/images.zip"

SCENES = ["bicycle", "bonsai", "counter", "drjohnson", "flowers", "garden", "kitchen",
          "playroom", "room", "stump", "train", "treehill", "truck"]

MODEL_FILES = ["cameras.json", "cfg_args", "point_cloud/iteration_30000/"]
EVAL_FILES = ["per_view.json", "results.json", "test/ours_30000/"]


def extract(url, out_dir, prefixes):
    """Extracts every archive entry starting with one of `prefixes` into out_dir."""
    print(f"reading index of {url}", flush=True)
    archive = zipfile.ZipFile(io.BufferedReader(HttpRangeFile(url), buffer_size=8 << 20))
    wanted = [i for i in archive.infolist()
              if not i.is_dir() and any(i.filename.startswith(p) for p in prefixes)]
    total = sum(i.file_size for i in wanted)
    done = 0
    for info in wanted:
        target = os.path.join(out_dir, info.filename)
        done += info.file_size
        if os.path.exists(target) and os.path.getsize(target) == info.file_size:
            continue
        os.makedirs(os.path.dirname(target), exist_ok=True)
        print(f"[{100 * done / max(total, 1):5.1f}%] {info.filename} ({info.file_size:,} bytes)", flush=True)
        # Write to a temp name so an interrupted file is never mistaken for a complete one.
        tmp = target + ".part"
        with archive.open(info) as src, open(tmp, "wb") as dst:
            shutil.copyfileobj(src, dst, 8 << 20)
        os.replace(tmp, target)

    found = {p.split("/")[0] for p in prefixes if any(i.filename.startswith(p) for i in wanted)}
    missing = sorted({p.split("/")[0] for p in prefixes} - found)
    if missing:
        print(f"warning: not found in {url}: {', '.join(missing)}", flush=True)
    print(f"done: {len(wanted)} files, {total / 2**30:.2f} GB in {out_dir}", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("scenes", nargs="*", help=f"scenes to fetch (default: all {len(SCENES)})")
    ap.add_argument("--data-dir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data"))
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--models-only", action="store_true")
    group.add_argument("--eval-only", action="store_true")
    args = ap.parse_args()

    scenes = args.scenes or SCENES
    unknown = [s for s in scenes if s not in SCENES]
    if unknown:
        ap.error(f"unknown scene(s): {', '.join(unknown)} (known: {', '.join(SCENES)})")

    data = os.path.normpath(args.data_dir)
    if not args.eval_only:
        extract(MODELS_URL, os.path.join(data, "models"),
                [f"{s}/{f}" for s in scenes for f in MODEL_FILES])
    if not args.models_only:
        extract(EVAL_URL, os.path.join(data, "eval"),
                [f"{s}/{f}" for s in scenes for f in EVAL_FILES])


if __name__ == "__main__":
    main()
